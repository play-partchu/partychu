// 휴대폰번호 정규화 — NICE 본인확인이 돌려주는 `mobile_no`를
// users/{uid}.phoneNumber에 저장하기 전에 한 가지 모양으로 맞춘다.
//
// ── 왜 E.164가 아니라 숫자만 남긴 국내 형식인가 ─────────────────────────────
// 저장 모양을 `01012345678`로 둔다. 이 값을 실제로 읽는 곳이 관리자 웹의
// 마스킹 표시 하나뿐인데(admin_app/lib/utils/masking.dart의 Masking.phone),
// 그 함수는 숫자만 남긴 뒤 **앞 3자리와 뒤 4자리**를 취한다. E.164(+8210…)로
// 저장하면 앞 3자리가 '821'이 되어 국가번호가 통신사 자리에 찍힌
// `821-****-5678`이 표시된다 — 관리자가 보는 값이 실제 번호와 달라진다.
//
// 앱이 저장하는 다른 전화번호(예약의 requesterPhone, 의견의 contactPhone)도
// 사용자가 적은 국내 표기 그대로 들어가므로, 국내 형식이 이 프로젝트 안에서
// 이미 일관된 쪽이기도 하다.
//
// ── 못 알아보면 저장하지 않는다 ────────────────────────────────────────────
// 형식이 어긋나면 빈 문자열을 돌려주고, 호출부는 그때 필드를 **아예 쓰지
// 않는다**. 반쯤 맞는 값을 남기면 나중에 "저장돼 있으니 맞는 번호겠지" 하고
// 그대로 쓰게 된다 — 연락이 닿지 않는 번호가 저장된 것보다, 없는 편이 낫다.
//
// ── 원문은 어디에도 남기지 않는다 ──────────────────────────────────────────
// 이 모듈은 로그를 찍지 않는다. 호출부도 번호 원문이 아니라 "정규화에
// 성공했는지"만 로그로 남긴다(niceAuth.js · index.js).
//
// ⚠ 이 파일은 순수 헬퍼다 — Cloud Function을 export하지 않는다
//   (identityGuard.js · applicantIdentity.js와 같은 컨벤션). 그래서 호출부는
//   `Object.assign(exports, require(...))`가 아니라 항상 구조분해로 가져다 쓴다.

/// 국내 휴대폰 번호로 인정하는 모양 — 010/011/016/017/018/019 + 7~8자리.
///
/// 010은 실제로 11자리뿐이지만 7자리도 받아 둔다. 여기는 통신사 번호부여
/// 규칙을 검사하는 자리가 아니라 **표기를 하나로 맞추는** 자리이고, 규칙을
/// 좁게 잡으면 알아볼 수 있는 번호를 이유 없이 버리게 된다.
const KOREAN_MOBILE = /^01[016789]\d{7,8}$/;

/**
 * 휴대폰번호를 `01012345678` 모양으로 맞춘다.
 *
 * 하이픈·공백·괄호는 전부 버리고, 국제 표기(+82)는 국내 표기로 되돌린다.
 * 국내 휴대폰 번호로 알아볼 수 없으면 **빈 문자열**을 돌려준다(예외를 던지지
 * 않는다 — 본인확인 자체는 번호와 무관하게 성립해야 하기 때문이다).
 *
 * @param {unknown} raw NICE 응답의 `mobile_no` 등 원본 값
 * @returns {string} 정규화된 번호, 또는 알아볼 수 없으면 ''
 */
function normalizeKoreanMobile(raw) {
  if (typeof raw !== 'string' && typeof raw !== 'number') return '';

  const digits = String(raw).replace(/[^0-9]/g, '');
  if (!digits) return '';

  // 국제 표기(+82 10 …)로 오는 경우까지 받아 둔다. 국내 번호는 항상 0으로
  // 시작하므로 '82'로 시작하는 값과 겹치지 않는다.
  //
  // '+82 010 …'처럼 국가번호 뒤에 0이 그대로 남아 오는 표기도 있어서, 떼어낸
  // 나머지가 이미 0으로 시작하면 0을 다시 붙이지 않는다(붙이면 '0010…'이
  // 되어 멀쩡한 번호가 버려진다).
  let domestic = digits;
  if (domestic.startsWith('82')) {
    const rest = domestic.slice(2);
    domestic = rest.startsWith('0') ? rest : `0${rest}`;
  }

  return KOREAN_MOBILE.test(domestic) ? domestic : '';
}

module.exports = { normalizeKoreanMobile, KOREAN_MOBILE };
