// ─────────────────────────────────────────────────────────────────────────────
// 🎬 웹에서 Cloudflare Stream 동영상을 재생하게 만드는 **단 하나의 자리**.
//
// ── 무엇이 문제였나 ──────────────────────────────────────────────────────────
// 서버가 저장하는 재생 주소는 HLS다(`…/manifest/video.m3u8` — mediaUploads.js의
// `streamPlaybackUrls`). 그런데 `video_player`의 웹 구현은 `<video src=…>`
// 엘리먼트 하나가 전부라, **HLS를 네이티브로 읽는 브라우저에서만** 재생된다.
// 그건 Safari/iOS뿐이고 Chrome·Edge·Firefox는 `MediaError code 4`
// (SRC_NOT_SUPPORTED)로 실패한다. 그래서 웹에서는 카드가 영상 대신 정지
// 썸네일에 머물렀다(썸네일 폴백 자체는 예전부터 있던 정상 동작이다).
//
// ── 왜 화면마다 고치지 않았나 ────────────────────────────────────────────────
// 앱 안에서 `VideoPlayerController.networkUrl(...)`을 만드는 곳은 일곱 군데다 —
// 목록 카드([VideoThumbnail])·상세 갤러리([MediaGallery])·상세페이지 블록
// 미리보기·블록 편집기·크롭 편집기·로컬 파일 재생([LocalMedia]). 여기에 각각
// "웹이면 다른 플레이어"를 넣으면 자동재생·음소거·썸네일 폴백·크롭 같은 UX가
// 일곱 벌로 갈라지고, 그중 하나만 고쳐지는 날이 반드시 온다.
//
// 그래서 **호출부는 한 줄도 건드리지 않는다.** 대신 그 아래 한 층
// (`VideoPlayerPlatform`)에서 갈아끼운다: 웹 플러그인이 만든 바로 그
// `<video>` 엘리먼트에 hls.js를 붙여, 컨트롤러가 보기에는 예전과 똑같은
// 엘리먼트가 되도록 한다. 재생·일시정지·음소거·seek·looping·크기 보고가 전부
// 원래 코드 그대로 흐르므로, 카드 UX는 손댈 것이 없다.
//
// ── 깨뜨리지 않는 것 ─────────────────────────────────────────────────────────
//   · Android / iOS — 이 파일의 웹 구현은 **컴파일조차 되지 않는다**(아래
//     조건부 import). [install]은 아무 일도 하지 않는 빈 함수다.
//   · Safari / iOS 웹 — 네이티브 HLS가 되는 브라우저에서는 hls.js를 붙이지
//     않고 예전 경로(`<video src>`)를 그대로 쓴다.
//   · HLS가 아닌 주소(mp4·blob: 로컬 미리보기) — 어느 브라우저에서도 그대로.
//   · hls.js를 못 불러온 경우 — 예전과 똑같이 동작한다(정지 썸네일 폴백).
//
// hls.js 자체는 `web/index.html`이 CDN에서 싣는다(cropper.js와 같은 방식).
// ─────────────────────────────────────────────────────────────────────────────

