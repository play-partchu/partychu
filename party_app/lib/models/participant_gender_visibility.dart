/// 게스트에게 **실제 참가자의 남녀 성비**를 보여줄지 — 호스트가 파티마다 켜고
/// 끄는 설정 하나(Firestore `revealParticipantGenderRatio`).
///
/// ## 무엇을 감추는가
/// 감추는 것은 **지금 참가한 사람들의 남/여 인원**뿐이다.
///
///   · 감춘다 — '남 5 / 여 3'처럼 현재 참가자의 성별 내역, 그리고 그 값을
///     **역산할 수 있는 값**(내 성별 기준 잔여 자리: 남자 정원 10에 잔여 2면
///     남자 참가자가 8명이라는 뜻이다).
///   · 감추지 않는다 — 현재 총 참가 인원과 모집 정원('8 / 20명'). 호스트가
///     정해 둔 **모집 조건**(남자 정원 10명 / 여자 정원 10명)도 그대로다.
///     이건 "누가 왔는가"가 아니라 "어떤 파티인가"라서 성격이 다르다.
///
/// ## 기존 파티와의 호환
/// 이 필드가 없던 파티는 지금까지 성비를 보여줬으므로 **없음 = 공개(true)**로
/// 읽는다([of]). 신규 등록 기본값도 공개다 — 새 설정이 생겼다고 이미 열려 있던
/// 파티의 화면이 바뀌면 안 된다.
///
/// ## 비로그인 정책과의 순서
/// 로그인 전에는 **현재 인원 자체가** 보이지 않는다(참가비·모집 상태와 같은
/// 기존 규칙). 그 정책이 먼저고, 이 설정은 그 관문을 통과한 **로그인 게스트**
/// 에게만 적용된다 — 둘은 겹치지 않는다.
///
/// ## 호스트는 예외
/// 이 설정은 게스트에게 나가는 정보만 제어한다. 호스트 본인이 보는 신청자·
/// 참가자 관리 화면과 자기 파티 상세에서는 그대로 보인다([revealsTo]).
class ParticipantGenderVisibility {
  ParticipantGenderVisibility._();

  /// Firestore 필드명. 뜻이 그대로 드러나는 boolean 하나로 통일한다.
  static const field = 'revealParticipantGenderRatio';

  /// 기본값 — 공개.
  static const defaultValue = true;

  /// 파티 문서에서 읽는다. **필드가 없으면 공개**(기존 파티 동작 유지).
  static bool of(Map<String, dynamic> data) =>
      data[field] as bool? ?? defaultValue;

  /// 지금 이 사람에게 현재 참가자의 남/여 인원을 보여도 되는가.
  ///
  /// 호스트는 설정과 무관하게 언제나 본다. 게스트는 호스트가 공개로 둔
  /// 파티에서만 본다.
  static bool revealsTo(Map<String, dynamic> data, {required bool isHost}) =>
      isHost || of(data);
}
