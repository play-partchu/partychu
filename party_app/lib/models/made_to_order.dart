// ─────────────────────────────────────────────────────────────────────────────
// 🛠 주문제작 — 파티샵 상품의 **불리언 하나**.
//
// ── 이것이 하는 일과 하지 않는 일 ────────────────────────────────────────────
// 하는 일은 하나뿐이다: "이 상품은 재고를 세지 않는다"를 표시한다.
//   · 호스트 — 재고 수량 대신 이 칸을 켠다(등록 화면의 체크란).
//   · 게스트 — 재고가 0이어도 품절로 막히지 않는다.
//   · 서버   — 재고 검사·차감을 건너뛴다(functions/shopOrders.js).
//
// 하지 않는 일:
//   · 주문 상태를 늘리지 않는다. `orders`의 상태는 예전 그대로
//     payment_pending → paid → cancelled/refunded/expired 다섯뿐이다.
//   · 호스트 승인 단계를 만들지 않는다. 상품 주문에는 원래 승인이 없고
//     (`requireApproval`은 파티 신청·예약에만 쓴다), 주문제작도 예외가 아니다.
//   · 결제·환불 흐름을 새로 만들지 않는다. 무통장입금·현장결제 그대로다.
//
// ── 문구를 여기 모아 두는 이유 ───────────────────────────────────────────────
// 같은 말이 등록 화면·상품 목록·구매 시트·주문 관리 네 군데에 나온다. 각자
// 적으면 한 곳만 고쳤을 때 "주문제작"과 "제작 주문"이 섞인다.
//
// ⚠️ 문구는 **지금 상태 머신이 실제로 하는 일**만 적는다.
//    · 주문은 접수 즉시 생성된다 — "주문을 확인해야 주문이 된다"고 쓰지 않는다.
//    · 호스트가 눌러야 넘어가는 칸은 무통장입금의 '입금 확인' 하나다
//      (functions/shopOrders.js 상단의 흐름도). 그래서 호스트 안내도 '제작
//      승인'이 아니라 **주문을 놓치지 않는 것**에 대해 말한다.
//    · 알림은 이 앱에서 필수가 아니다([PushPermissionGate]는 조르지 않는다) —
//      "켜야 한다"가 아니라 "확인해 주세요"로 적는다.
// ─────────────────────────────────────────────────────────────────────────────

/// Firestore `partyShops/{shopId}/products/{productId}.madeToOrder`.
///
/// **필드가 없으면 false**다 — 기존 상품은 전부 재고 상품 그대로다.
const String kMadeToOrderField = 'madeToOrder';

/// 🛠 — 주문제작을 한 글자로 가리키는 표시. 배지·칩이 전부 이 이모지를 쓴다.
const String kMadeToOrderEmoji = '🛠';

const String kMadeToOrderLabel = '주문제작';

/// 배지 문구 — '🛠 주문제작'.
const String kMadeToOrderBadge = '$kMadeToOrderEmoji $kMadeToOrderLabel';

/// 이 상품이 무엇인지 한 줄. 호스트가 켤 때도, 게스트가 볼 때도 같은 말이다.
const String kMadeToOrderNotice = '주문이 들어오면 제작하는 상품이에요.';

/// 호스트에게만 덧붙이는 한 줄.
///
/// '알림을 켜야 한다'가 아니다 — 앱이 알림을 강제하지 않으므로 단정하면
/// 사실과 어긋난다. 진입점은 마이페이지 > 알림 설정 하나이고, 그 화면이
/// 이미 켜짐/꺼짐과 켜는 방법을 모두 보여준다.
const String kMadeToOrderHostNotice = '주문을 놓치지 않도록 알림 설정을 확인해 주세요.';

/// 게스트 구매 화면의 환불 안내.
///
/// 환불 **정책을 바꾸지 않는다** — 지금 규칙 그대로이고, 이 줄은 주문제작
/// 상품에서 생길 수 있는 일을 미리 알려 줄 뿐이다. 그래서 '제한됩니다'가
/// 아니라 '제한될 수 있어요'다.
const String kMadeToOrderRefundNotice =
    '제작이 시작된 이후에는 단순 변심에 의한 취소·환불이 제한될 수 있어요.';

/// 상품 문서 하나가 주문제작인가 — 읽는 규칙의 **정본**.
///
/// 앱·서버·집계가 전부 이 판정을 거친다. 필드가 없거나 bool이 아니면 false다
/// (예전 문서에는 필드 자체가 없다).
bool isMadeToOrderProduct(Map<String, dynamic>? data) =>
    data != null && data[kMadeToOrderField] == true;

/// 이 상품을 **살 수 있는가** — 재고 판정의 정본.
///
/// 주문제작은 재고를 세지 않으므로 `stock`이 0이어도 살 수 있다. 재고 상품은
/// 예전 그대로 0이면 품절이다. 서버도 같은 규칙으로 막는다
/// (functions/shopOrders.js — madeToOrder면 재고 검사·차감을 건너뛴다).
bool shopProductInStock({required int stock, required bool madeToOrder}) =>
    madeToOrder || stock > 0;
