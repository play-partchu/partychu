    ...securitiesNames,
  });

  static String? nameOf(String? code) => code == null ? null : names[code];

  /// 요약 한 줄 — `'카카오뱅크 ****1234'`.
  ///
  /// **본인 화면의 요약·목록에는 언제나 이 형태를 쓴다.** 계좌번호 전체는
  /// 상대가 이체해야 하는 자리(무통장입금 안내)에서만 그린다 — 마이페이지처럼
  /// 어깨너머로 읽힐 수 있는 곳에서 전체 번호를 다시 그릴 이유가 없다.
  ///
  /// 수취계좌([PayoutAccount.maskedSummary])와 환불계좌
  /// ([RefundAccount.maskedSummary])가 **같은 함수**를 쓴다 — 두 곳에 따로
  /// 적으면 한쪽만 자릿수나 기호가 바뀌어 같은 화면에서 다른 모양이 된다.
  ///
  /// 네 자리보다 짧은 계좌번호는 있는 만큼만 남기고, 번호가 없으면 기관명만
  /// 돌려준다(둘 다 비면 빈 문자열).
  static String maskedSummary({String? bankName, String? accountNumber}) {
    final bank = (bankName ?? '').trim();
    final digits = (accountNumber ?? '').replaceAll(RegExp(r'[^0-9]'), '');
    if (digits.isEmpty) return bank;
    final tail = digits.length <= 4
        ? digits
        : digits.substring(digits.length - 4);
    return bank.isEmpty ? '****$tail' : '$bank ****$tail';
  }

  /// 이름으로 코드를 되찾는다 — 코드 없이 이름만 저장돼 있던 예전 정산계좌를
  /// 수취계좌 화면이 프리필할 때만 쓴다(그 외에는 언제나 코드가 정본이다).
  static String? codeOf(String? bankName) {
    final name = (bankName ?? '').trim();
    if (name.isEmpty) return null;
    for (final entry in names.entries) {
      if (entry.value == name) return entry.key;
    }
    return null;
  }
